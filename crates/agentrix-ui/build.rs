//! Embeds the kit's templates, static files and words into the binary, and stamps a content
//! version on the static files so pages can cache `/static/ui/*?v=…` as immutable.
//!
//! Every file under `templates/` becomes a template named by its path (`ui/kit.html`), and
//! every file under `static/` an asset served by its path (`fonts/manrope-latin-wght-normal.woff2`).
//! Adding a file needs no code change.

use std::fmt::Write as _;
use std::hash::{DefaultHasher, Hash, Hasher};
use std::{
    env, fs,
    path::{Path, PathBuf},
};

fn files(dir: &Path, out: &mut Vec<PathBuf>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    for entry in fs::read_dir(dir).unwrap_or_else(|e| panic!("reading {}: {e}", dir.display())) {
        let path = entry.expect("directory entry is readable").path();
        if path.is_dir() {
            files(&path, out);
        } else if !path
            .file_name()
            .is_some_and(|n| n.to_string_lossy().starts_with('.'))
        {
            out.push(path);
        }
    }
}

fn rel(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .expect("file is under its root")
        .to_string_lossy()
        .replace('\\', "/")
}

/// Drops comments and the whitespace CSS doesn't need. Enough for token files: no strings
/// with significant runs of spaces, no `content:` values.
fn minify(css: &str) -> String {
    let mut out = String::with_capacity(css.len());
    let mut rest = css;
    while let Some(start) = rest.find("/*") {
        out.push_str(&rest[..start]);
        rest = rest[start..]
            .find("*/")
            .map_or("", |end| &rest[start + end + 2..]);
    }
    out.push_str(rest);
    let collapsed = out.split_whitespace().collect::<Vec<_>>().join(" ");
    let mut tight = String::with_capacity(collapsed.len());
    let chars: Vec<char> = collapsed.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if c == ' ' {
            let prev = if i > 0 { chars[i - 1] } else { '{' };
            let next = chars.get(i + 1).copied().unwrap_or('}');
            if "{};:,>".contains(prev) || "{};:,>".contains(next) {
                continue;
            }
        }
        tight.push(c);
    }
    tight.replace(";}", "}")
}

fn main() {
    let manifest =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let mut out = String::from("// Generated by build.rs. Do not edit.\n");

    let templates_root = manifest.join("templates");
    let mut templates = Vec::new();
    files(&templates_root, &mut templates);
    templates.sort();
    out.push_str(
        "/// Every kit template, as (name, source).\npub static TEMPLATES: &[(&str, &str)] = &[\n",
    );
    for path in &templates {
        println!("cargo:rerun-if-changed={}", path.display());
        writeln!(
            out,
            "    ({:?}, include_str!({:?})),",
            rel(&templates_root, path),
            path.display().to_string()
        )
        .expect("writing to a String");
    }
    out.push_str("];\n");

    // The tokens have two sources: brand.css (the Agentrix layer, served alone for pages with a
    // tight budget) and extended.css (latin-ext faces, the shell's surfaces, the site layer).
    // tokens.css, which every layout links, is the two joined. Both are served minified, written
    // to OUT_DIR, so there is one copy of each token and the sources keep their comments.
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let tokens_root = manifest.join("tokens");
    let read = |name: &str| {
        let path = tokens_root.join(name);
        println!("cargo:rerun-if-changed={}", path.display());
        fs::read_to_string(&path).unwrap_or_else(|e| panic!("reading {}: {e}", path.display()))
    };
    let (brand, extended) = (minify(&read("brand.css")), minify(&read("extended.css")));
    let brand_path = out_dir.join("brand.css");
    let tokens_path = out_dir.join("tokens.css");
    fs::write(&brand_path, &brand).expect("writing brand.css");
    fs::write(&tokens_path, format!("{brand}{extended}")).expect("writing tokens.css");

    let static_root = manifest.join("static");
    let mut assets: Vec<(String, PathBuf)> = Vec::new();
    let mut found = Vec::new();
    files(&static_root, &mut found);
    for path in found {
        assets.push((rel(&static_root, &path), path));
    }
    assets.push(("brand.css".into(), brand_path));
    assets.push(("tokens.css".into(), tokens_path));
    assets.sort();
    let mut hasher = DefaultHasher::new();
    out.push_str("/// Every static file, as (path under /static/ui/, bytes).\npub static ASSETS: &[(&str, &[u8])] = &[\n");
    for (name, path) in &assets {
        println!("cargo:rerun-if-changed={}", path.display());
        name.hash(&mut hasher);
        fs::read(path)
            .unwrap_or_else(|e| panic!("reading {}: {e}", path.display()))
            .hash(&mut hasher);
        writeln!(
            out,
            "    ({name:?}, include_bytes!({:?})),",
            path.display().to_string()
        )
        .expect("writing to a String");
    }
    out.push_str("];\n");

    let words = manifest.join("words");
    let mut word_files = Vec::new();
    files(&words, &mut word_files);
    word_files.sort();
    out.push_str("/// The words catalogue, one JSON file per language, as (language, source).\npub static WORDS: &[(&str, &str)] = &[\n");
    for path in &word_files {
        println!("cargo:rerun-if-changed={}", path.display());
        let lang = path
            .file_stem()
            .expect("a words file has a name")
            .to_string_lossy()
            .to_string();
        writeln!(
            out,
            "    ({lang:?}, include_str!({:?})),",
            path.display().to_string()
        )
        .expect("writing to a String");
    }
    out.push_str("];\n");

    let dest = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("embedded.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("writing {}: {e}", dest.display()));
    println!(
        "cargo:rustc-env=AGENTRIX_UI_VERSION={:012x}",
        hasher.finish() & 0xffff_ffff_ffff
    );
}
