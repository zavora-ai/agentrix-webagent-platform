// Generates packages/agentrix_kit/lib/src/tokens.g.dart from W7's design tokens
// (crates/agentrix-ui/tokens/brand.css) and the samples' brand themes
// (crates/agentrix-themes/static/{kilele,classy,tana}.css), so the apps never retype a colour.
//
//   cd apps && dart run tool/tokens.dart
import 'dart:io';

final _decl = RegExp(r'--([a-z0-9-]+)\s*:\s*([^;]+);');

/// The declarations inside the first block whose selector starts with `selector`.
Map<String, String> block(String css, String selector) {
  final start = css.indexOf(selector);
  if (start < 0) throw StateError('no block $selector');
  final open = css.indexOf('{', start);
  var depth = 0;
  var end = open;
  for (var i = open; i < css.length; i++) {
    if (css[i] == '{') depth++;
    if (css[i] == '}') {
      depth--;
      if (depth == 0) {
        end = i;
        break;
      }
    }
  }
  final body = css.substring(open + 1, end);
  return {for (final m in _decl.allMatches(body)) m[1]!: m[2]!.trim()};
}

String color(String hex) {
  var h = hex.trim().replaceFirst('#', '');
  if (h.length == 3) h = h.split('').map((c) => '$c$c').join();
  if (h.length != 6) throw FormatException('not a hex colour: $hex');
  return 'Color(0xFF${h.toUpperCase()})';
}

String camel(String name) {
  final parts = name.split('-');
  return parts.first +
      parts.skip(1).map((p) => p.isEmpty ? '' : p[0].toUpperCase() + p.substring(1)).join();
}

const brandKeys = [
  'indigo', 'indigo-900', 'indigo-700', 'indigo-100', 'indigo-50', 'coral', 'coral-strong',
  'coral-50', 'ink', 'ink-2', 'muted', 'line', 'line-strong', 'paper', 'surface', 'surface-2',
  'ok', 'ok-bg', 'wait', 'wait-bg', 'risk', 'risk-bg',
];

const waKeys = ['wa-bg', 'wa-soft', 'wa-ink', 'wa-ink-2', 'wa-line', 'wa-accent', 'wa-accent-2', 'wa-on-accent'];

void main() {
  final root = File(Platform.script.toFilePath()).parent.parent.parent.path;
  final brand = File('$root/crates/agentrix-ui/tokens/brand.css').readAsStringSync();
  final light = block(brand, ':root {');
  final dark = {...light, ...block(brand, ':root[data-theme="dark"]')};
  final out = StringBuffer()
    ..writeln('// GENERATED by apps/tool/tokens.dart from crates/agentrix-ui/tokens/brand.css and')
    ..writeln('// crates/agentrix-themes/static/*.css. Do not edit; run `dart run tool/tokens.dart`.')
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln()
    ..writeln('/// The Agentrix colours, light (by day) and dark (Night Time).')
    ..writeln('class AgxColors {')
    ..writeln('  const AgxColors({${brandKeys.map((k) => 'required this.${camel(k)}').join(', ')}});');
  for (final k in brandKeys) {
    out.writeln('  final Color ${camel(k)};');
  }
  for (final (name, map) in [('light', light), ('dark', dark)]) {
    out.writeln('  static const $name = AgxColors(');
    for (final k in brandKeys) {
      out.writeln('    ${camel(k)}: ${color(map[k]!)},');
    }
    out.writeln('  );');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// A sample site\'s own brand (the `--wa-*` tokens its WebAgent components inherit).')
    ..writeln('class SiteBrand {')
    ..writeln('  const SiteBrand({required this.id, required this.name, required this.display, ${waKeys.map((k) => 'required this.${camel(k.substring(3))}').join(', ')}});')
    ..writeln('  final String id;')
    ..writeln('  final String name;')
    ..writeln('  /// The display face for headings.')
    ..writeln('  final String display;');
  for (final k in waKeys) {
    out.writeln('  final Color ${camel(k.substring(3))};');
  }
  out.writeln('}');
  const sites = [
    ('kilele', 'Kilele Bakery', 'kilele.css', '.bake', 'Fraunces'),
    ('classy', 'Classy Perfumes', 'classy.css', '.shop', 'CormorantGaramond'),
    ('tana', 'Tana Valley Times', 'tana.css', '.tana', 'LibreCaslonText'),
  ];
  for (final (id, name, file, selector, display) in sites) {
    final css = File('$root/crates/agentrix-themes/static/$file').readAsStringSync();
    final m = block(css, '$selector {');
    out
      ..writeln()
      ..writeln('const $id = SiteBrand(')
      ..writeln("  id: '$id',")
      ..writeln("  name: '$name',")
      ..writeln("  display: '$display',");
    for (final k in waKeys) {
      out.writeln('  ${camel(k.substring(3))}: ${color(m[k]!)},');
    }
    out.writeln(');');
  }
  out
    ..writeln()
    ..writeln('/// Every sample brand, by id.')
    ..writeln("const siteBrands = {'kilele': kilele, 'classy': classy, 'tana': tana};");
  final target = File('${File(Platform.script.toFilePath()).parent.parent.path}/packages/agentrix_kit/lib/src/tokens.g.dart');
  target.parent.createSync(recursive: true);
  target.writeAsStringSync(out.toString());
  stdout.writeln('wrote ${target.path}');
}
